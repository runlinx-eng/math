// Fail-closed native-source + full runtime fingerprint + real view-control preflight.
// Development gate only; never grants formal strict A or edits main.
import {mkdirSync,writeFileSync} from 'node:fs';
import {resolve,dirname} from 'node:path';
import {pathToFileURL} from 'node:url';
import {createHash} from 'node:crypto';
const stable=v=>Array.isArray(v)?v.map(stable):v&&typeof v==='object'?
 Object.fromEntries(Object.keys(v).sort((a,b)=>a.localeCompare(b,'en')).map(k=>[k,stable(v[k])])):v;
const digest=v=>createHash('sha256').update(JSON.stringify(stable(v))).digest('hex');
const nativeModule=rel=>import(pathToFileURL(resolve(rel)).href);
const receipt={schema:'math-a-native-preflight/1',case:process.env.A_DEV_CASE||null,
 candidateHead:process.env.A_DEV_HEAD||null,status:'FAIL',strictAApproved:false,native:[],errors:[]};
const out=resolve('dev-results/native-preflight.json');
function save(){mkdirSync(dirname(out),{recursive:true});writeFileSync(out,JSON.stringify(receipt,null,2)+'\n');}
async function main(){
 try{
  const specs=JSON.parse(process.env.A_DEV_NATIVE_JSON||'null');
  if(!Array.isArray(specs)||specs.length===0)throw Error('native target specifications missing');
  const [{sessionTaskFor,BRIDGES},{LESSONS}]=await Promise.all([
   nativeModule('dist/learning/bridges.js'),nativeModule('dist/learning/catalog.js')]);
  for(const s of specs){
   const position=s.sessionId+':'+s.index;
   if(!Object.hasOwn(LESSONS,s.sessionId))throw Error(position+' not registered in original catalog');
   if(Object.hasOwn(BRIDGES,s.sessionId))throw Error(position+' is a bridge, not native');
   if(LESSONS[s.sessionId].topicId!==s.nodeId)throw Error(position+' native source node mismatch');
   const task=sessionTaskFor(s.sessionId,s.index);
   if(!task||typeof task!=='object')throw Error(position+' original native runtime task unavailable');
   if(task.type!==s.type)throw Error(position+' task type mismatch');
   const actual=digest(task);
   receipt.native.push({position,nodeId:s.nodeId,type:task.type,expectedSha256:s.taskSha256,
    actualSha256:actual,hashMatched:actual===s.taskSha256});
   if(actual!==s.taskSha256)throw Error(position+' full SHA256 mismatch: expected '+s.taskSha256+' got '+actual);
   if(s.view){
    const [model,view]=await Promise.all([
     nativeModule('dist/learning/phase5/'+s.view+'-model.js'),
     nativeModule('dist/learning/phase5/'+s.view+'-view.js')]);
    if(typeof model.initial!=='function'||typeof view.controls!=='function'||
     typeof view.visual!=='function')throw Error(position+' native UI source exports unavailable');
    const m=model.initial(task,314159);
    const markup=String(view.controls(task,m))+String(view.visual(task,m));
    for(const action of s.controls){
     if(!markup.includes('data-x="'+action+'"'))throw Error(position+' UI action '+action+' not generated by original view');
    }
    receipt.native.at(-1).uiActionsChecked=[...s.controls];
   }
  }
  receipt.status='PASS';save();
  console.log('A_DEV_NATIVE_PREFLIGHT_PASS '+JSON.stringify({case:receipt.case,head:receipt.candidateHead,
   count:receipt.native.length,positions:receipt.native.map(x=>x.position)}));
 }catch(error){
  receipt.errors.push(String(error?.stack||error));save();
  console.error('A_DEV_NATIVE_PREFLIGHT_FAIL '+String(error?.message||error));
  process.exitCode=1;
 }
}
await main();
