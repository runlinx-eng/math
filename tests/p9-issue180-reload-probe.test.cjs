'use strict';
// Synthetic instrumentation contract, not a substitute for real Chromium.
const test=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const os=require('node:os');
const path=require('node:path');
const {EventEmitter}=require('node:events');
const crypto=require('node:crypto');
const {createReloadStartupProbe}=require('./helpers/p9-issue180-reload-probe.cjs');

test('preserves native first failure and SW fallback without truncating the journal',async t=>{
 const out=fs.mkdtempSync(path.join(os.tmpdir(),'math-p9-reload-probe-'));
 t.after(()=>fs.rmSync(out,{recursive:true,force:true}));
 const network=new EventEmitter();
 network.send=async domain=>assert.equal(domain,'Network.enable');
 network.detach=async()=>{};
 const nativeSW=new EventEmitter();
 nativeSW.send=async domain=>{assert.equal(domain,'ServiceWorker.enable');throw Error("Protocol error: 'ServiceWorker.enable' wasn't found");};
 nativeSW.detach=async()=>{};
 const worker=new EventEmitter();
 worker.url=()=> 'http://127.0.0.1:1234/sw.js';
 const context=new EventEmitter();
 context.newCDPSession=async()=>network;
 context.browser=()=>({newBrowserCDPSession:async()=>nativeSW});
 context.serviceWorkers=()=>[worker];
 const page=new EventEmitter();
 page.viewportSize=()=>({width:1280,height:720});
 let reads=0;
 page.evaluate=async()=>({readyState:'complete',raw:'historical-record-'+(++reads),entryCached:true});
 const probe=createReloadStartupProbe({context,page,out,cache:'test-release'});
 await probe.start();
 network.emit('Network.requestWillBeSent',{requestId:'1',type:'Script',request:{url:'http://127.0.0.1:1234/learning/learn.js'}});
 network.emit('Network.loadingFailed',{requestId:'1',type:'Script',errorText:'net::ERR_ABORTED',canceled:true});
 for(let i=0;i<850;i++)network.emit('Network.requestWillBeSent',{requestId:'r'+i,type:'Document',request:{url:'http://127.0.0.1:1234/learn.html'}});
 worker.emit('close');
 const before=await probe.snapshot();
 await probe.failure({label:'synthetic-failure',before,error:new Error('original failure')});
 const journalPath=path.join(out,'1280x720-native-startup-network.jsonl');
 const journalAtFailure=fs.readFileSync(journalPath);
 assert.equal(page.listenerCount('requestfailed'),1);
 assert.equal(page.listenerCount('console'),1);
 assert.equal(worker.listenerCount('close'),1);
 // Late events can arrive after persistence but before close() finishes.
 worker.emit('close');
 page.emit('console',{type:()=> 'error',text:()=> 'late-before-close'});
 network.emit('Network.loadingFailed',{requestId:'late',errorText:'net::ERR_ABORTED'});
 assert.deepEqual(fs.readFileSync(journalPath),journalAtFailure,'journal must freeze at persistence, before cleanup');
 await probe.close();
 assert.equal(page.listenerCount('requestfailed'),0);
 assert.equal(page.listenerCount('console'),0);
 assert.equal(worker.listenerCount('close'),0);
 assert.equal(context.listenerCount('serviceworker'),0);
 page.emit('requestfailed',{url:()=> 'http://127.0.0.1/late.js',failure:()=>({errorText:'late'}),resourceType:()=> 'script'});
 page.emit('console',{type:()=> 'error',text:()=> 'late console error'});
 worker.emit('close');
 assert.deepEqual(fs.readFileSync(journalPath),journalAtFailure,'post-close events must not alter the finalized journal');
 const json=JSON.parse(fs.readFileSync(path.join(out,'synthetic-failure-native-startup.json'),'utf8'));
 const bytes=fs.readFileSync(path.join(out,'1280x720-native-startup-network.jsonl'));
 const events=bytes.toString('utf8').trimEnd().split('\n').map(JSON.parse);
 assert.equal(json.status,'failure');
 assert.equal(json.journal.complete,true);
 assert.equal(json.journal.eventCount,events.length);
 assert.equal(json.journal.lineCount,events.length);
 assert.equal(json.journal.sha256,crypto.createHash('sha256').update(bytes).digest('hex'));
 assert.deepEqual(events.map(x=>x.seq),Array.from({length:events.length},(_,i)=>i+1));
 assert.equal(json.eventsTailTruncated,true);
 assert.equal(json.events.length,700);
 assert.equal(json.firstFailures[0].kind,'loadingFailed');
 assert.equal(json.firstFailures[0].errorText,'net::ERR_ABORTED');
 assert.equal(json.firstFailures[0].canceled,true);
 assert.equal(json.firstFailures[0].request.url,'http://127.0.0.1:1234/learning/learn.js');
 assert.equal(json.serviceWorkerObservation.nativeCdpEvents,false);
 assert.equal(json.serviceWorkerObservation.playwrightWorkerEvents,true);
 assert.equal(json.serviceWorkerObservation.playwrightWorkersObserved,1);
 assert.equal(events.some(x=>x.kind==='playwrightServiceWorker'&&x.existing),true);
 assert.equal(events.some(x=>x.kind==='playwrightServiceWorkerClosed'),true);
 assert.equal(events.some(x=>x.kind==='serviceWorkerSessionError'),true);
 assert.equal(events.some(x=>x.kind==='serviceWorkerObservationCapabilities'&&!x.nativeCdpEvents),true);
 assert.equal(json.rawIdentical,false);
 assert.equal(fs.readFileSync(path.join(out,'synthetic-failure-native-startup-before-storage.txt'),'utf8'),'historical-record-1');
 assert.equal(fs.readFileSync(path.join(out,'synthetic-failure-native-startup-after-storage.txt'),'utf8'),'historical-record-2');
 assert.equal(context.listenerCount('serviceworker'),0);
});
