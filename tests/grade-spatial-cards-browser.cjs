// Relationship-first grade hierarchy: source-backed desktop acceptance.
const fs=require('node:fs'),path=require('node:path');
const {chromium}=require(process.env.MATH_PLAYWRIGHT_MODULE||'playwright');
const out=path.resolve(__dirname,'../verification/grade-spatial-cards');
const url='http://127.0.0.1:43827/?world=network&layout=53#atlas';
const checks=[],errors=[];
const check=(ok,msg)=>{if(!ok)throw Error(msg);checks.push(msg);};
(async()=>{
 fs.mkdirSync(out,{recursive:true});
 const browser=await chromium.launch({headless:true,args:['--use-angle=swiftshader','--enable-unsafe-swiftshader']});
 const context=await browser.newContext({viewport:{width:1440,height:900},reducedMotion:'reduce'});
 const page=await context.newPage();page.on('pageerror',e=>errors.push(e.stack||String(e)));
 try{
   await page.goto(url);
   await page.waitForFunction(()=>window.mathSpace&&mathSpace.snapshot().visibleNodes.length===537);
   const pose=()=>page.evaluate(()=>{const x=mathSpace.snapshot();return JSON.stringify({position:x.position,target:x.target,zoom:x.cameraZoom,positions:x.positions});});
   const before=await pose();
   await page.locator('[data-action="observation-mode"][data-mode="grade"]').click();
   await page.waitForFunction(()=>document.querySelectorAll('.grade-pack-row').length===23&&mathSpace.snapshot().gradeSpatial.structureStats?.roots===29);
   const snap=await page.evaluate(()=>mathSpace.snapshot().gradeSpatial);
   check(snap.stages===3&&snap.packs===23&&snap.nodes===537,'full 3-stage, 23-group, 537-node source model is present');
   check(snap.structureStats.hardEdges===808&&snap.structureStats.roots===29&&snap.structureStats.leaves===156,'root and leaf counts use genuine hard-edge classification');
   check(await page.locator('.grade-stage-selector [data-action="grade-spatial-stage-select"]').count()===3,'three fixed two-year stage controls are visible');
   check(await page.locator('.grade-stage-selector').isVisible(),'stage lens is permanently docked in the sidebar');
   check(await page.locator('[data-action="grade-select"]').count()===6,'six year entrances remain available behind an optional disclosure');
   check(await page.locator('.grade-spatial-stage:visible').count()===0,'no stage cards float over the map');
   check(await page.locator('.grade-spatial-pack:visible').count()===0,'no group cards float over the map');
   check(await page.locator('#grade-matrix-panel').isHidden(),'original 23 by 3 matrix starts collapsed');
   check(await page.locator('.grade-space-pack').count()===23,'all 23 original groups are reachable by curriculum priority');
   check(await page.locator('.grade-space-other').count()>=1,'secondary groups are progressive-disclosure content');
   check(await page.locator('.grade-bone-path').count()>0,'source-grounded root-to-trunk paths replace floating cards');
   await page.waitForFunction(()=>document.querySelectorAll('.overview-structure-lines .structure-path.grade-trunk').length>=2);
   const source=await page.evaluate(async()=>({
     graph:await(await fetch('./data/atlas.json')).json(),
     grade:await(await fetch('./data/grade-progression.json')).json()
   }));
   const hard=new Set(source.graph.edges.filter(e=>e.strength==='hard').map(e=>e.prerequisiteId+'>'+e.topicId));
   const edges=await page.evaluate(()=>mathSpace.snapshot().gradeSpatial.pathEdges);
   check(edges.length>=5&&edges.every(e=>hard.has(e.from+'>'+e.to)),'every visible stage backbone edge is a real prerequisite');
   check((await pose())===before,'grade mode leaves the original 3D coordinates and camera unchanged');
   await page.screenshot({path:path.join(out,'01-stage-hover.png')});
   await page.locator('.grade-stage-selector [data-grade="3"]').hover();
   await page.waitForFunction(()=>mathSpace.snapshot().gradeSpatial.hoveredStageId==='stage-2');
   check((await page.evaluate(()=>mathSpace.snapshot().gradeSpatial)).highlightedNodeCount===259,'hover previews precisely the selected stage membership');
   check((await pose())===before,'hover temporarily previews without camera motion');
   await page.screenshot({path:path.join(out,'02-stage-selected.png')});
   await page.locator('.grade-stage-selector [data-grade="3"]').click();
   await page.waitForFunction(()=>mathSpace.snapshot().gradeSpatial.selectedStageId==='stage-2'&&mathSpace.snapshot().gradeSpatial.hoveredStageId===null);
   check((await page.evaluate(()=>mathSpace.snapshot().gradeSpatial)).focusKind==='stage','click fixes the chosen stage');
   check(await page.locator('.grade-bone-path').count()>0,'stage two renders authentic source root/trunk examples');
   check(await page.locator('.grade-space-pack').count()===23,'stage switch preserves all 23 groups');
   check(await pose()===before,'stage selection is camera-stable');
   await page.screenshot({path:path.join(out,'desktop-spatial-cards.png')});
   const group=page.locator('.grade-space-pack[data-pack-id="add-subtract"]');
   await group.hover();await page.waitForFunction(()=>mathSpace.hoverPreview().key==='pack:add-subtract');
   check(await pose()===before,'group hover changes highlight only');
   await group.click();
   await page.waitForFunction(()=>mathSpace.snapshot().selected==='pack:add-subtract'&&mathSpace.snapshot().gradeSpatial.focusKind==='pack');
   check(await page.locator('#focus-card .grade-space-node').count()>0,'group click opens original knowledge-point membership');
   check((await page.locator('#focus-card .grade-space-pack-nodes').innerText()).includes('跨群真实联系'),'group detail distinguishes actual cross-group relations');
   const groupBox=await page.locator('#focus-card').boundingBox(),guideBox=await page.locator('#network-guide').boundingBox();
   check(!!groupBox&&!!guideBox&&groupBox.x>guideBox.x+guideBox.width+24&&groupBox.x+groupBox.width<=1440,'desktop detail stays right of the fixed stage panel');
   check(await pose()===before,'group click preserves camera and node coordinates');
   await page.screenshot({path:path.join(out,'03-group-selected.png')});
   await page.locator('#focus-card [data-action="grade-space-node-select"][data-node-id="mt_s2mfRBoTal"]').click();
   await page.waitForFunction(()=>mathSpace.snapshot().selected==='node:mt_s2mfRBoTal');
   check(await page.locator('#focus-card .network-relations').count()>0,'node click preserves actual prerequisite/follow-on navigation');
   check(await page.locator('#focus-card [data-action="grade-space-return-pack"]').count()===1,'node detail can return to its group');
   check(await pose()===before,'node click remains in the original spatial position');
   await page.screenshot({path:path.join(out,'04-node-detail.png')});
   await page.locator('#focus-card [data-action="grade-space-return-pack"]').click();
   await page.waitForFunction(()=>mathSpace.snapshot().selected==='pack:add-subtract');
   await page.locator('#focus-card [data-action="grade-space-return-stage"]').click();
   await page.waitForFunction(()=>mathSpace.snapshot().gradeSpatial.focusKind==='stage'&&!mathSpace.snapshot().selected);
   await page.locator('[data-action="grade-matrix-toggle"]').click();
   check(await page.locator('#grade-matrix-panel').isVisible()&&await page.locator('.grade-pack-row').count()===23,'complete source curriculum matrix remains accessible');
   await page.screenshot({path:path.join(out,'05-matrix-expanded.png')});
   await page.locator('[data-action="grade-matrix-toggle"]').click();
   check(await page.locator('#grade-matrix-panel').isHidden(),'matrix can return to quiet panorama');
   await page.locator('[data-action="observation-mode"][data-mode="relationship"]').click();
   check(await page.locator('#grade-observation-view').isHidden(),'original relationship panorama remains intact');
   check(await pose()===before,'return to relationship panorama keeps original pose');
   check(errors.length===0,'no uncaught browser errors: '+errors.join(' | '));
   console.log(JSON.stringify({passed:checks.length,checks},null,2));
 }catch(error){
   console.error(error.stack||String(error));console.error('Browser errors:',errors);
   await page.screenshot({path:path.join(out,'failure.png')}).catch(()=>{});
   process.exitCode=1;
 }finally{await browser.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
